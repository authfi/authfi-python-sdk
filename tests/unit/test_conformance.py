"""The conformance vectors every AuthFI SDK runs (``conformance/vectors.json``).

The file is generated by the Node SDK's ``scripts/gen-vectors.mjs`` and copied here byte for byte:
tokens signed by throwaway keys, each with the outcome and refusal code every SDK must produce. A
token that one SDK accepts and another refuses is how an API behind two of them decides differently.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import httpx
import pytest

from authfi import AuthFI, InvalidToken
from tests.support import FakeClock

DIRECTORY = Path(__file__).resolve().parents[2] / "conformance"
DOCUMENT: dict[str, Any] = json.loads((DIRECTORY / "vectors.json").read_text(encoding="utf-8"))
VECTORS: list[dict[str, Any]] = DOCUMENT["vectors"]


def test_the_vectors_are_the_file_that_was_published() -> None:
    text = (DIRECTORY / "vectors.json").read_bytes()
    recorded = (DIRECTORY / "vectors.json.sha256").read_text(encoding="utf-8").split()[0]
    assert hashlib.sha256(text).hexdigest() == recorded


def project() -> AuthFI:
    issuer = DOCUMENT["issuer"]

    def answer(request: httpx.Request) -> httpx.Response:
        if request.url.path.endswith("/jwks.json"):
            return httpx.Response(200, json=DOCUMENT["jwks"])
        return httpx.Response(
            200,
            json={
                "issuer": issuer,
                "token_endpoint": f"{issuer}/oauth/token",
                "jwks_uri": f"{issuer}/.well-known/jwks.json",
            },
        )

    clock = FakeClock(wall=float(DOCUMENT["now"]))
    return AuthFI(
        issuer,
        http_client=httpx.Client(transport=httpx.MockTransport(answer)),
        clock=clock,
        leeway=float(DOCUMENT["leeway_seconds"]),
    )


@pytest.mark.parametrize("vector", VECTORS, ids=[v["name"] for v in VECTORS])
def test_vector(vector: dict[str, Any]) -> None:
    verifier = project().verifier(audience=DOCUMENT["audience"], expected_tenant_id=DOCUMENT["tenant_id"])
    expected = vector["expect"]
    if not expected["valid"]:
        with pytest.raises(InvalidToken) as caught:
            verifier.verify(vector["token"])
        assert caught.value.code == expected["code"]
        return
    token = verifier.verify(vector["token"])
    assert str(token.principal) == expected["principal"]
    assert token.token_kind == expected["token_kind"]
    assert (str(token.actor) if token.actor else None) == expected["actor"]
    if "client_id" in expected:
        assert token.client_id == expected["client_id"]
    if "scopes" in expected:
        assert sorted(token.scopes) == sorted(expected["scopes"])
