"""Generate ``src/authfi/_codes.py`` from the AuthFI kernel's refusal vocabulary.

The verifier's codes are the kernel's (``constants/http.go`` and package ``dpop``), so a code in a
platform log, an audit record and this SDK's ``InvalidToken.code`` is one spelling. The kernel is
read from a local checkout at a pinned tag::

    python scripts/gen_codes.py --kernel ../platform-kernel            # write the file
    python scripts/gen_codes.py --kernel ../platform-kernel --check    # fail if it differs

``--tag`` overrides the pinned tag. The drift job runs ``--check`` against the newest tag, so a
kernel release that changes the list is seen before the SDK speaks a stale vocabulary.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

#: The kernel tag the committed file was generated from.
PINNED_TAG = "v0.58.0"

SOURCES = ("constants/http.go", "dpop/dpop.go")

# A Go string constant whose value is a token or DPoP refusal code.
_CONST = re.compile(r'^\s*\w+\s*=\s*"((?:token|dpop_proof)_[a-z0-9_]+)"', re.MULTILINE)

#: Codes the SDK produces that the kernel does not have yet (filed to the kernel, L20).
SDK_ONLY = ("token_act_chain_unsupported",)

#: The OAuth and HTTP-authentication codes the SDK's errors carry, by the RFC that registers them.
REGISTERED = (
    # RFC 6749 §5.2
    "invalid_request",
    "invalid_client",
    "invalid_grant",
    "unauthorized_client",
    "unsupported_grant_type",
    "invalid_scope",
    # RFC 6749 §4.1.2.1
    "access_denied",
    "unsupported_response_type",
    "server_error",
    "temporarily_unavailable",
    # RFC 8707
    "invalid_target",
    # OpenID CIBA §11
    "authorization_pending",
    "slow_down",
    "expired_token",
    # RFC 6750 §3.1, RFC 9470
    "invalid_token",
    "insufficient_scope",
    "insufficient_user_authentication",
    # OpenID Connect Core §3.1.2.6
    "login_required",
    "consent_required",
    "interaction_required",
    # The kernel's opaque wire answers
    "unauthorized",
    "forbidden",
)

OUT = Path(__file__).resolve().parent.parent / "src" / "authfi" / "_codes.py"


def kernel_codes(kernel: Path, tag: str) -> list[str]:
    """Every token_* and dpop_proof_* code the kernel defines at ``tag``, in source order."""
    codes: list[str] = []
    for source in SOURCES:
        text = subprocess.run(
            ["git", "-C", str(kernel), "show", f"{tag}:{source}"],
            check=True,
            capture_output=True,
            encoding="utf-8",
        ).stdout
        for code in _CONST.findall(text):
            if code not in codes:
                codes.append(code)
    if not codes:
        raise SystemExit(f"no refusal codes found in {kernel} at {tag}: has the kernel layout changed?")
    return codes


def render(tag: str, codes: list[str]) -> str:
    """The module text for ``codes``."""
    known = [*codes, *SDK_ONLY, *REGISTERED]

    def literal(values: list[str] | tuple[str, ...]) -> str:
        return "\n".join(f'    "{v}",' for v in values)

    return f'''"""The refusal and error codes AuthFI uses. GENERATED by scripts/gen_codes.py; do not edit.

Kernel tag: {tag}. A code is an open set: compare against these, and keep a default arm for a code
this release does not know.
"""

from typing import Final, Literal

#: The kernel tag these codes were generated from.
KERNEL_TAG: Final = "{tag}"

#: Every code this SDK names: the kernel's token and DPoP refusals, the SDK's own, and the
#: registered OAuth and HTTP-authentication codes.
KnownCode = Literal[
{literal(known)}
]

#: The kernel's token and DPoP refusal codes, in the kernel's order.
KERNEL_TOKEN_CODES: Final[tuple[str, ...]] = (
{literal(codes)}
)

#: Codes this SDK produces that the kernel does not define yet.
SDK_TOKEN_CODES: Final[tuple[str, ...]] = (
{literal(SDK_ONLY)}
)
'''


def main(argv: list[str] | None = None) -> int:
    """Write or check the generated module."""
    parser = argparse.ArgumentParser(description="Generate src/authfi/_codes.py from the kernel.")
    parser.add_argument("--kernel", type=Path, required=True, help="a checkout of the platform kernel library")
    parser.add_argument("--tag", default=PINNED_TAG)
    parser.add_argument("--check", action="store_true", help="fail when the committed file differs")
    args = parser.parse_args(argv)
    text = render(args.tag, kernel_codes(args.kernel, args.tag))
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} differs from the kernel at {args.tag}; run scripts/gen_codes.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
